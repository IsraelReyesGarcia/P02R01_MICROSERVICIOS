BEGIN TRANSACTION;
BEGIN TRY
	IF EXISTS(
		SELECT 1 
		FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'Productos'
		AND TABLE_SCHEMA = 'dbo'
	)
		BEGIN
			DROP TABLE dbo.Productos;
			PRINT 'Tabla Productos eliminada correctamente'	
		END
	ELSE
		BEGIN
			PRINT 'La tabla [dbo].[Productos] no existe'
		END
	COMMIT TRANSACTION;
END TRY
BEGIN CATCH
	IF @@TRANCOUNT > 0
	ROLLBACK TRANSACTION
	THROW;
END CATCH
GO

